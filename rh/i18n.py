_lang = "en"


def set_lang(code):
    global _lang
    _lang = code if code in STR else "en"


def T(key):
    return STR[_lang].get(key) or STR["en"].get(key, key)


def lang_label(code):
    """UI 언어와 같으면 '한국어', 다르면 'English (영어)' 처럼 직관적으로 표시."""
    if code == "auto":
        return T("auto")
    if code == _lang:
        return NATIVE[code]
    return f"{NATIVE[code]} ({NAME_IN[_lang][code]})"
